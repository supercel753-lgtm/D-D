import assert from 'node:assert/strict';
import {mod,prof,derived,roll,rollAttributes,RACES,CLASSES,abilityScores} from '../data/rules.js';
import {validateData,importData} from '../services/storage.js';
import {CREATURES,SPELLS} from '../data/catalog.js';
assert.equal(mod(8),-1);
assert.equal(mod(10),0);
assert.equal(mod(15),2);
assert.equal(mod(20),5);
assert.equal(prof(1),2);
assert.equal(prof(4),2);
assert.equal(prof(5),3);
assert.equal(prof(9),4);
assert.equal(prof(13),5);
assert.equal(prof(17),6);
const base={str:15,dex:14,con:13,int:12,wis:10,cha:8};
const dwarf={base,race:'Anão',subrace:'Colina',className:'Guerreiro',level:1};
assert.equal(derived(dwarf).startingHP,13); // d10 + mod(CON=15)=2 + resiliência colina 1
assert.equal(derived(dwarf).defaultAC,12);
assert.equal(derived(dwarf).speed,7.5);
const elf={base,race:'Elfo',subrace:'Alto',className:'Mago',level:1};
assert.equal(abilityScores(elf).dex,16);
assert.equal(derived(elf).startingHP,7);
const half={base,race:'Meio-Elfo',subrace:'Padrão',flexible:['str','wis'],className:'Bardo',level:1};
assert.equal(abilityScores(half).str,16);
assert.equal(abilityScores(half).wis,11);
assert.equal(abilityScores(half).cha,10);
assert.equal(roll('3d6+2',()=>0).total,5);
assert.equal(roll('2d20-3',()=>0.999).total,37);
assert.throws(()=>roll('100d6'));
assert.throws(()=>roll('Math.random()'));
assert.equal(rollAttributes(()=>0).length,6);
assert.equal(Object.keys(RACES).length,9);
assert.equal(Object.keys(CLASSES).length,12);
assert.equal(CREATURES.length,8);
assert.ok(SPELLS.length>5);
const sample={version:1,characters:[],campaigns:[],sessions:[],notes:[],encounters:[],creatures:[],favorites:[],settings:{backendUrl:''}};
assert.equal(validateData(sample),sample);
assert.throws(()=>importData('{nope'),SyntaxError);
assert.throws(()=>validateData({version:1,characters:{}}));
console.log('PASS 25+ assertions: regras, dados, rolagens, schema e referências.');
